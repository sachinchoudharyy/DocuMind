import shutil
import uuid
from pathlib import Path

import fitz

from app.config import settings
from app.ingestion.document_loader import PDFDocumentLoader
from app.ingestion.text_splitter import DocumentChunker
from app.memory.session_manager import SessionManager
from app.vectorstore.faiss_store import FAISSVectorStore


class DocumentService:
    """
    Owns PDF upload, metadata, per-session files, and per-session FAISS indexes.

    Each session has an isolated upload directory and vector index directory.
    This service deliberately rebuilds an index from that session's registered
    PDFs, so deleted documents cannot remain as stale vectors.
    """

    MAX_FILE_BYTES = 20 * 1024 * 1024  # 20 MiB per PDF

    def __init__(
        self,
        session_manager: SessionManager | None = None,
        upload_root: str | Path | None = None,
        index_root: str | Path | None = None,
    ):
        self.sessions = session_manager or SessionManager()
        self.upload_root = Path(upload_root or Path(settings.DATA_DIR) / "uploads")
        self.index_root = Path(index_root or settings.VECTOR_DB_DIR)
        self.upload_root.mkdir(parents=True, exist_ok=True)
        self.index_root.mkdir(parents=True, exist_ok=True)
        self.loader = PDFDocumentLoader()
        self.chunker = DocumentChunker()

    @staticmethod
    def _safe_display_filename(filename: str) -> str:
        # Remove any client-supplied path components and control characters.
        cleaned = Path(filename.replace("\\", "/")).name
        cleaned = "".join(ch for ch in cleaned if ch.isprintable()).strip()
        if not cleaned or cleaned in {".", ".."}:
            raise ValueError("A valid PDF filename is required.")
        if Path(cleaned).suffix.lower() != ".pdf":
            raise ValueError("Only PDF files are accepted.")
        return cleaned[:180]

    @staticmethod
    def _validate_pdf(content: bytes):
        if not isinstance(content, (bytes, bytearray)) or not content:
            raise ValueError("The uploaded file is empty.")
        if len(content) > DocumentService.MAX_FILE_BYTES:
            raise ValueError("PDF exceeds the 20 MiB upload limit.")
        # A valid PDF header is required; parsing below catches malformed files.
        if b"%PDF-" not in bytes(content[:1024]):
            raise ValueError("The uploaded file does not have a valid PDF header.")
        try:
            with fitz.open(stream=bytes(content), filetype="pdf") as pdf:
                if pdf.page_count < 1:
                    raise ValueError("The PDF contains no pages.")
        except Exception as exc:
            if isinstance(exc, ValueError):
                raise
            raise ValueError("The uploaded PDF is unreadable or corrupted.") from exc

    def _session_upload_dir(self, session_id: str) -> Path:
        # UUID session IDs are generated by SessionManager; resolve guards path escape.
        directory = (self.upload_root / session_id).resolve()
        root = self.upload_root.resolve()
        if root not in directory.parents:
            raise ValueError("Invalid session identifier.")
        return directory

    def _session_index_dir(self, session_id: str) -> Path:
        directory = (self.index_root / session_id).resolve()
        root = self.index_root.resolve()
        if root not in directory.parents:
            raise ValueError("Invalid session identifier.")
        return directory

    def list_documents(self, session_id: str) -> list[dict]:
        return [
            {
                "document_id": item["document_id"],
                "filename": item["original_filename"],
                "size_bytes": item["size_bytes"],
                "uploaded_at": item["uploaded_at"],
            }
            for item in self.sessions.get_documents(session_id)
        ]

    def upload_pdf(self, session_id: str, filename: str, content: bytes) -> dict:
        if not self.sessions.session_exists(session_id):
            raise ValueError(f"Unknown chat session: {session_id}")
        display_name = self._safe_display_filename(filename)
        self._validate_pdf(content)

        session_dir = self._session_upload_dir(session_id)
        session_dir.mkdir(parents=True, exist_ok=True)
        stored_name = f"{uuid.uuid4().hex}_{display_name}"
        destination = session_dir / stored_name
        destination.write_bytes(bytes(content))

        document_id = None
        try:
            document_id = self.sessions.add_document(
                session_id=session_id,
                original_filename=display_name,
                stored_path=str(destination.resolve()),
                size_bytes=len(content),
            )
            # Rebuild only this session's index. A failed rebuild rolls back the
            # new database row and file, preserving the previously registered PDFs.
            self.rebuild_session_index(session_id)
        except Exception:
            if document_id:
                self.sessions.delete_document(session_id, document_id)
            destination.unlink(missing_ok=True)
            raise

        return {
            "document_id": document_id,
            "filename": display_name,
            "size_bytes": len(content),
            "status": "uploaded_and_indexed",
        }

    def _load_session_chunks(self, session_id: str):
        records = self.sessions.get_documents(session_id)
        documents = []
        for record in records:
            path = Path(record["stored_path"]).resolve()
            session_dir = self._session_upload_dir(session_id).resolve()
            if session_dir not in path.parents or not path.is_file():
                raise FileNotFoundError(
                    f"Registered PDF is missing or outside its session folder: "
                    f"{record['original_filename']}"
                )
            pages = self.loader.load_pdf(str(path))
            for page in pages:
                page.metadata["source"] = record["original_filename"]
                page.metadata["document_id"] = record["document_id"]
                page.metadata["file_path"] = str(path)
            documents.extend(pages)

        if not documents:
            return [], []
        chunks = self.chunker.split_documents(documents)
        for chunk in chunks:
            chunk.metadata.setdefault("document_id", None)
        return documents, chunks

    def rebuild_session_index(self, session_id: str):
        if not self.sessions.session_exists(session_id):
            raise ValueError(f"Unknown chat session: {session_id}")
        _, chunks = self._load_session_chunks(session_id)
        index_dir = self._session_index_dir(session_id)

        if not chunks:
            shutil.rmtree(index_dir, ignore_errors=True)
            return None

        # Build in a temporary sibling directory first. Swap only after the
        # new index is complete, so a failed embedding run does not corrupt the
        # previously usable session index (important on Windows as well).
        temporary_dir = index_dir.with_name(
            f"{index_dir.name}.tmp_{uuid.uuid4().hex}"
        )
        backup_dir = index_dir.with_name(
            f"{index_dir.name}.backup_{uuid.uuid4().hex}"
        )
        shutil.rmtree(temporary_dir, ignore_errors=True)
        temporary_dir.mkdir(parents=True, exist_ok=True)
        try:
            store = FAISSVectorStore(index_path=temporary_dir)
            store.create_index(chunks)
            store.save_index()

            if index_dir.exists():
                index_dir.rename(backup_dir)
            try:
                temporary_dir.rename(index_dir)
            except Exception:
                if backup_dir.exists() and not index_dir.exists():
                    backup_dir.rename(index_dir)
                raise
            shutil.rmtree(backup_dir, ignore_errors=True)
        except Exception:
            shutil.rmtree(temporary_dir, ignore_errors=True)
            raise

        # The in-memory store points to the directory now renamed to index_dir;
        # its FAISS object is already loaded and remains valid for this process.
        store.index_path = index_dir
        return store, chunks

    def load_session_index(self, session_id: str):
        """
        Return (FAISSVectorStore, chunks) for this session.

        PDF text is re-extracted to rebuild chunk metadata for contextual
        retrieval. Existing FAISS vectors are loaded when present; otherwise
        the session index is created. This avoids loading a global index.
        """
        if not self.sessions.session_exists(session_id):
            raise ValueError(f"Unknown chat session: {session_id}")
        _, chunks = self._load_session_chunks(session_id)
        if not chunks:
            return None

        index_dir = self._session_index_dir(session_id)
        store = FAISSVectorStore(index_path=index_dir)
        if (index_dir / "index.faiss").exists():
            store.load_index()
        else:
            store.create_index(chunks)
            store.save_index()
        return store, chunks

    def delete_document(self, session_id: str, document_id: str) -> bool:
        record = self.sessions.get_document(session_id, document_id)
        if record is None:
            return False

        deleted = self.sessions.delete_document(session_id, document_id)
        if deleted is None:
            return False

        path = Path(deleted["stored_path"]).resolve()
        session_dir = self._session_upload_dir(session_id).resolve()
        if session_dir in path.parents:
            path.unlink(missing_ok=True)

        # Rebuild after the DB row is removed, so deleted content is excluded.
        self.rebuild_session_index(session_id)
        try:
            session_dir.rmdir()
        except OSError:
            pass
        return True

    def delete_session_files(self, session_id: str):
        """Call before/after SessionManager.delete_session when removing a chat."""
        shutil.rmtree(self._session_upload_dir(session_id), ignore_errors=True)
        shutil.rmtree(self._session_index_dir(session_id), ignore_errors=True)
